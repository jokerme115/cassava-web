def _resolve_optional_model_path(env_name, default_path=None):
    raw_value = os.getenv(env_name, '').strip()
    if not raw_value:
        return default_path
    if os.path.isabs(raw_value):
        return raw_value
    return os.path.abspath(os.path.join(BASE_DIR.parent, raw_value))


